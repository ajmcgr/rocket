await assert.rejects(call('stripe_payments'),/purchases/);
assert.equal((await db.query('select is_current from connect_developer_accounts')).rows[0].is_current,true);
await db.exec('delete from connect_transactions');
await db.exec("insert into connect_checkout_attempts values('client',now()+interval '1 hour')");
await assert.rejects(call('stripe_payments'),/checkouts/);
