import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const pg = new PGlite();
await pg.exec(`create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create schema app_graph;
create table auth.users(id uuid primary key);
create table app_graph.apps(id uuid primary key,is_public boolean default true);
create view public.public_apps as select id from app_graph.apps where is_public;
create table public.app_owners(app_id uuid,user_id uuid,verification_level text,revoked_at timestamptz);
grant usage on schema auth,app_graph to service_role;
grant all on all tables in schema auth,app_graph,public to service_role;
`);
await pg.exec(readFileSync('supabase/migrations/20260929075313_slice3_stripe_revenue_verification.sql','utf8'));
await pg.exec(readFileSync('supabase/migrations/20261026092747_stripe_account_mrr_scope.sql','utf8'));
const owner='10000000-0000-4000-8000-000000000001',other='10000000-0000-4000-8000-000000000002';
const app='20000000-0000-4000-8000-000000000001',app2='20000000-0000-4000-8000-000000000002';
await pg.query('insert into auth.users values($1),($2)',[owner,other]);
await pg.query('insert into app_graph.apps(id) values($1),($2)',[app,app2]);
await pg.query("insert into public.app_owners values($1,$2,'domain_verified',null),($3,$4,'domain_verified',null)",[app,owner,app2,other]);
const connection=async(user,account)=>(await pg.query(`insert into public.app_revenue_connections(owner_user_id,provider,external_account_id,livemode,status,refresh_token_ciphertext,refresh_token_iv,last_successful_sync) values($1,'stripe',$2,true,'active','fixture','fixture',now()) returning id`,[user,account])).rows[0].id;
const c=await connection(owner,'acct_shared'),c2=await connection(other,'acct_shared');
const bind=(a,c,u)=>pg.query('select public.bind_app_revenue_connection($1,$2,$3)',[a,c,u]);
const price=(id)=>({price_id:id,product_id:'prod_fixture',currency:'usd'});
const configure=(a,c,u,scope,prices,version=null)=>pg.query('select public.configure_app_stripe_revenue($1,$2,$3,$4,$5,$6) version',[a,c,u,scope,prices,version]);
await pg.exec('set role service_role');
await bind(app,c,owner);
await pg.query("update public.app_revenue_bindings set visibility='exact' where app_id=$1",[app]);
await assert.rejects(configure(app,c,other,'account',[price('price_first')]));
await assert.rejects(configure(app,c,owner,'invalid',[price('price_first')]));
let version=(await configure(app,c,owner,'account',[price('price_first')],0)).rows[0].version;
assert.equal((await pg.query('select visibility from public.app_revenue_bindings where app_id=$1',[app])).rows[0].visibility,'private','scope change revokes visibility');
await assert.rejects(bind(app2,c2,other),'a different user cannot bind an account already assigned as a total');
await assert.rejects(configure(app,c,owner,'account',[price('price_second')],0),'stale sync fails CAS');
await pg.query("update public.app_revenue_bindings set visibility='range' where app_id=$1",[app]);
version=(await configure(app,c,owner,'account',[price('price_first'),price('price_new')],version)).rows[0].version;
assert.equal((await pg.query('select visibility from public.app_revenue_bindings where app_id=$1',[app])).rows[0].visibility,'range','new-price discovery in same scope retains consent');
await pg.query(`insert into public.app_revenue_metric_points(app_id,connection_id,provider,metric_type,currency,mrr_minor,mapping_version,included_subscriptions,excluded_subscriptions,unsupported_subscriptions,verification_status,calculation_version,source_livemode,observed_at) values($1,$2,'stripe','subscription_mrr','usd',10000,$3,1,0,0,'verified',1,true,now())`,[app,c,version]);
await pg.query('select public.refresh_app_revenue_projection($1)',[app]);
assert.equal((await pg.query('select revenue_scope from public.public_app_revenue where app_id=$1',[app])).rows[0].revenue_scope,'account');
await configure(app,c,owner,'products',[price('price_first')],version);
assert.equal((await pg.query('select count(*)::int n from public.public_app_revenue where app_id=$1',[app])).rows[0].n,0,'switching scope removes stale public total');
await bind(app2,c2,other);
await assert.rejects(configure(app,c,owner,'account',[price('price_first')]),'account scope cannot absorb another app binding');
await assert.rejects(configure(app2,c2,other,'products',[price('price_first')]),'same Stripe price cannot be claimed through another user connection');
await configure(app2,c2,other,'products',[price('price_different')]);
await pg.query('update public.app_owners set revoked_at=now() where app_id=$1',[app2]);
await assert.rejects(configure(app2,c2,other,'products',[price('price_different')]));
for(const role of ['anon','authenticated']){
 await pg.exec(`reset role;set role ${role}`);
 await assert.rejects(configure(app,c,owner,'account',[price('price_first')]));
 await assert.rejects(pg.query('select * from public.latest_app_revenue_scope_points($1,$2)',[app,version]));
}
await pg.close();
console.log('PASS: account exclusivity across users, product isolation, CAS, owner checks, visibility reset, fresh-price discovery, public scope labelling and service-only RPCs');
